#!/usr/bin/env node
// Embeds public/ (the runtime's browser files) into src/assets.generated.ts, so a site serves
// them from its Worker bundle without copying anything into its own public/. The bytes served
// are exactly the source files: this is packaging, not a build. Runs on install, before tests
// and type checks, and on prepack; the output is gitignored.
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url).pathname;
const pub = join(root, 'public');

/**
 * The live preview SDK, vendored for the browser: `@contentworker/sdk/live-preview`'s published
 * ESM build and the chunks it imports, copied unchanged into public/scripts/vendor/sdk/ (still
 * no bundler: its imports are relative files, so they resolve beside it). Rewritten from
 * node_modules on every run, gitignored, and packed with the runtime. A sibling .d.ts re-exports
 * the package's types, so tsconfig.browser.json checks our calls against them.
 */
function vendorLivePreview(): string[] {
  const entry = fileURLToPath(import.meta.resolve('@contentworker/sdk/live-preview'));
  const from = dirname(entry);
  const to = join(pub, 'scripts/vendor/sdk');
  rmSync(to, { recursive: true, force: true });
  mkdirSync(to, { recursive: true });
  const copied: string[] = [];
  const queue = [entry.slice(from.length + 1)];
  while (queue.length) {
    const name = queue.shift() as string;
    if (copied.includes(name)) continue;
    const source = readFileSync(join(from, name), 'utf8');
    for (const m of source.matchAll(/(?:\bfrom|\bimport)\s*["'](\.\/[^"']+)["']/g)) {
      const dep = (m[1] as string).slice(2);
      if (dep.includes('/')) throw new Error(`vendor: ${name} imports ${dep}, not a sibling file`);
      queue.push(dep);
    }
    if (/\bimport\s*\(|\brequire\s*\(|from\s*["'](?!\.\/)/.test(source))
      throw new Error(`vendor: ${name} imports something other than a sibling file`);
    copyFileSync(join(from, name), join(to, name));
    copied.push(name);
  }
  writeFileSync(
    join(to, 'live-preview.d.ts'),
    "// Generated by scripts/embed-assets.ts. Types for the vendored build.\nexport * from '@contentworker/sdk/live-preview';\n",
  );
  return copied;
}

const vendored = vendorLivePreview();
const TYPES: Record<string, string> = {
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2',
};

function* walk(dir: string): Generator<string> {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* walk(path);
    else yield path;
  }
}

const entries: string[] = [];
for (const file of [...walk(pub)].sort()) {
  const ext = extname(file);
  if (ext === '.ts' || !TYPES[ext]) continue; // server-side block halves and unknown files stay out
  const path = `/${relative(pub, file)}`;
  const binary = ext === '.woff2';
  const body = binary ? readFileSync(file).toString('base64') : readFileSync(file, 'utf8');
  entries.push(
    `  ${JSON.stringify(path)}: { type: ${JSON.stringify(TYPES[ext])}, base64: ${binary}, body: ${JSON.stringify(body)} },`,
  );
}

writeFileSync(
  join(root, 'src/assets.generated.ts'),
  `// Generated by scripts/embed-assets.ts from public/. Do not edit.\nexport interface EmbeddedAsset {\n  type: string;\n  base64: boolean;\n  body: string;\n}\n\nexport const EMBEDDED: Record<string, EmbeddedAsset> = {\n${entries.join('\n')}\n};\n`,
);
console.log(
  `embedded ${entries.length} runtime assets (vendored @contentworker/sdk/live-preview: ${vendored.join(', ')})`,
);
